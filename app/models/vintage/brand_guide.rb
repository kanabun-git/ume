    def self.find(slug)
      BRANDS.find { |brand| brand[:slug] == slug }
    end

    # Claudeに渡す参考情報。画面のガイドと同じ知識を、プロンプトに収まる
    # 長さのプレーンテキストへ畳んだもの。
    def self.reference_text
      common = COMMON_CLUES.map { |clue| "- #{clue[:title]}: #{clue[:body]}" }.join("\n")
      brands = BRANDS.map do |brand|
        eras = brand[:eras].map { |era| "    - #{era[:label]}: #{era[:clue]}" }.join("\n")
        "- #{brand[:name]}\n#{eras}"
      end.join("\n")

      "## 年代判定の共通の手がかり\n#{common}\n\n## ブランド別のタグ変遷\n#{brands}"
    end
